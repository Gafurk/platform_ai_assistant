def _build_intent_handling(lang: str) -> str:
    blocks: list[str] = []

    # Handcrafted blocks first (in a stable order)
    for sid in (
        "tu_application", "real_estate",
        "supply_contract_residential", "supply_contract_non_residential",
        "primary_connection_residential", "primary_connection_nonresidential",
    ):
        block = _HANDCRAFTED_BLOCKS[sid][lang]
        blocks.append(block)

    # Generated blocks for all remaining services (alphabetical order is stable)
    for service_id in _registry.list_services():
        if service_id not in _SPECIAL_INTENTS:
            block = _generic_intent_block(service_id, lang)
            if block:
                blocks.append(block)

    # Fallback for no-intent FAQ mode
    if lang == "kz":
        blocks.append(
            "=== ЕГЕР интент анықталмаса ===\n"
            "FAQ ретінде жұмыс іст — контекст негізінде жауап бер, жағдай немесе қадам таңдау туралы нақтылау сұрақтарын қойма."
        )
        entity_rule = (
            "ОПРЕДЕЛЕНИЕ ФЛ/ЮЛ (ЖТ/ЗТ) — барлық интенттер үшін:\n"
            "- Тип пользователя передаётся в <intent_context>.\n"
            "- НИКОГДА не спрашивай пользователя о его типе лица повторно."
        )
    else:
        blocks.append(
            "=== ЕСЛИ интент не определён ===\n"
            "Работай как FAQ — отвечай на основе контекста, не задавай уточняющих вопросов о выборе ситуации или шага."
        )
        entity_rule = (
            "ОПРЕДЕЛЕНИЕ ФЛ/ЮЛ (для всех интентов):\n"
            "- Тип пользователя передаётся в <intent_context>.\n"
            "- НИКОГДА не спрашивай пользователя о его типе лица повторно."
        )
    blocks.append(entity_rule)

    header = "НАЗАР АУДАРЫҢЫЗ — <intent_context> ішіндегі Интентке қатаң тармақтау:" if lang == "kz" \
        else "ВНИМАНИЕ — строгое ветвление по Интенту из <intent_context>:"
    return header + "\n\n" + "\n\n".join(blocks)


