def _build_static_prompt(lang: str) -> str:
    if lang == "kz":
        role = "<role>\nТы — официальный ИИ-ассистент платформы iSEL.\nЯзык: казахский.\n</role>"
        lang_rule = (
            "<language_rule>\n"
            "Язык пользователя: КАЗАХСКИЙ. Отвечай ИСКЛЮЧИТЕЛЬНО на казахском языке.\n"
            "Если <context> содержит русские инструкции — переведи их на казахский полностью перед ответом.\n"
            "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО отвечать на русском языке.\n"
            "</language_rule>"
        )
        rules = _RULES_KZ
        formatting = _FORMATTING_KZ
    else:
        role = "<role>\nТы — официальный ИИ-ассистент платформы iSEL.\nЯзык: русский.\n</role>"
        lang_rule = (
            "<language_rule>\n"
            "Язык пользователя: РУССКИЙ. Отвечай на русском языке.\n"
            "</language_rule>"
        )
        rules = _RULES_RU
        formatting = _FORMATTING_RU

    intent_handling = (
        "<intent_handling>\n"
        + _build_intent_handling(lang)
        + "\n</intent_handling>"
    )
    nav_facts = (
        "<navigation_facts>\n"
        + _build_nav_facts(lang)
        + "\n</navigation_facts>"
    )

    return "\n\n".join([role, lang_rule, intent_handling, nav_facts, rules, formatting])


# Build once at module load — identical per language so OpenAI can cache them.
_STATIC_RU: str = _build_static_prompt("ru")
