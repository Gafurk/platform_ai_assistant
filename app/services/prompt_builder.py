"""PromptBuilder — assembles system prompts from templates + ServiceRegistry config.

Navigation facts and service labels come from services.yaml (single source of truth).
Generic FAQFlow service sections are generated from a shared template so adding a
new FAQFlow service requires only a YAML edit — no changes here.
Complex services (tu_application, real_estate, supply contracts) use handcrafted rules.
"""
