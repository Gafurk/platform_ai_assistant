def _build_static_prompt(lang: str) -> str:
    if lang == "kz":
        role = "<role>\nТы — официальный ИИ-ассистент платформы iSEL.\nЯзык: казахский.\n</role>"
        lang_rule = (
            "<language_rule>\n"
            "Язык пользователя: КАЗАХСКИЙ. Отвечай ИСКЛЮЧИТЕЛЬНО на казахском языке.\n"
            "Если <context> содержит русские инструкции — переведи их на казахский полностью перед ответом.\n"
            "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО отвечать на русском языке.\n"
            "</language_rule>"
        )
        rules = _RULES_KZ
        formatting = _FORMATTING_KZ
    else:
        role = "<role>\nТы — официальный ИИ-ассистент платформы iSEL.\nЯзык: русский.\n</role>"
        lang_rule = (
            "<language_rule>\n"
            "Язык пользователя: РУССКИЙ. Отвечай на русском языке.\n"
            "</language_rule>"
        )
        rules = _RULES_RU
        formatting = _FORMATTING_RU

    intent_handling = (
        "<intent_handling>\n"
        + _build_intent_handling(lang)
        + "\n</intent_handling>"
    )
    nav_facts = (
        "<navigation_facts>\n"
        + _build_nav_facts(lang)
        + "\n</navigation_facts>"
    )

    return "\n\n".join([role, lang_rule, intent_handling, nav_facts, rules, formatting])


# Build once at module load — identical per language so OpenAI can cache them.
_STATIC_RU: str = _build_static_prompt("ru")
_STATIC_KZ: str = _build_static_prompt("kz")


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def build_system_prompt(
    language: str,
    history: str,
    intent: Optional[str],
    entity: Optional[str],
    current_step: Optional[int],
    page: Optional[str],
    situation: Optional[str] = None,
) -> str:
    """Return the full system prompt for a single LLM request.

    The static base (role, rules, navigation facts, intent handling) is
    pre-built at startup and never recomputed. Only the dynamic tail
    (history, intent_context, step_control) is assembled per request.
    """
    static = _STATIC_KZ if language == "kz" else _STATIC_RU
    dynamic_parts: list[str] = []

    if history:
        dynamic_parts.append(f"<history>\n{history}\n</history>")

    if intent or entity or page or situation:
        svc = _registry.get_service(intent or "")
        intent_label = (
            svc.display_name.get(language) or svc.display_name.get("ru")
            if svc else "не определён"
        )
        ctx_lines = [
            f"Интент: {intent_label}",
            f"Тип пользователя: {entity or 'не определено'}",
            f"Страница: {page or 'не указана'}",
        ]
        if situation:
            ctx_lines.append(f"Выбранная ситуация: {situation}")
        dynamic_parts.append(
            "<intent_context>\n" + "\n".join(ctx_lines) + "\n</intent_context>"
        )

    if current_step is not None:
        svc = _registry.get_service(intent or "")
        max_steps = (svc.flow.max_steps or 5) if svc else 5

        # FIX #3: Add mandatory fields checker for load_calculation step 3
        ren_checklist = ""
        if intent == "load_calculation" and current_step == 3:
            ren_checklist = "\n\n" + (_REN_STEP3_MANDATORY_FIELDS_KZ if language == "kz" else _REN_STEP3_MANDATORY_FIELDS_RU)

        if current_step < max_steps:
            if language == "kz":
                step_note = (
                    "Егер нұсқаулықта «Әрі қарай» батырмасы туралы ескерту жоқ болса — "
                    "соңына қос: «Барлық міндетті өрістерді толтырғаннан кейін "
                    "келесі қадамға өту үшін **Әрі қарай** батырмасын басыңыз.»"
                )
            else:
                step_note = (
                    "Если инструкция шага не содержит фразу о нажатии «Далее» — добавь в конце: "
                    "«После заполнения всех обязательных полей нажмите кнопку **Далее**, "
                    "чтобы перейти к следующему шагу.»"
                )
        else:
            step_note = (
                f"Это ПОСЛЕДНИЙ шаг. Дай инструкцию по подписи и отправке. "
                f"НИКОГДА не предлагай шаг {max_steps + 1}. "
                "После инструкции добавь: «После отправки статус заявки и готовые ТУ появятся в "
                "**Личный кабинет → Услуги → вкладка Обращения**.»"
            )
        dynamic_parts.append(
            f"<step_control>\n"
            f"Текущий шаг: {current_step} из {max_steps}\n"
            f"Отвечай СТРОГО по шагу {current_step}. Не включай другие шаги.\n"
            f"{step_note}\n"
            f"</step_control>{ren_checklist}"
        )

    if dynamic_parts:
        return static + "\n\n" + "\n\n".join(dynamic_parts)
    return static