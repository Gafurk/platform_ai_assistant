# ---------------------------------------------------------------------------
# Navigation facts — built once from ServiceRegistry at module load
# ---------------------------------------------------------------------------

def _build_nav_facts(lang: str) -> str:
    lines: list[str] = []
    for svc in _registry.list_services().values():
        nav = svc.navigation_path.get(lang) or svc.navigation_path.get("ru") or ""
        if nav:
            label = svc.display_name.get(lang) or svc.display_name.get("ru") or svc.service_id
            lines.append(f"{label}: {nav}")
    if lang == "kz":
        lines += [
            "Өтініш мәртебесі мен дайын құжаттар: Жеке кабинет → **Қызметтер** → **Өтініштер** қосымша беті",
            "ТШ немесе дәлелді бас тартуды жүктеу: **Өтініштер** кестесіндегі жолды тауып → **Жүктеу** немесе **Қарау** батырмасын басу",
        ]
    else:
        lines += [
            "Статус заявки и готовые документы: Личный кабинет → **Услуги** → вкладка **Обращения**",
            "Скачать ТУ или мотивированный отказ: найти строку в таблице **Обращения** → нажать иконку **Скачать** или кнопку **Просмотр**",
        ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Generic intent_handling block (FAQFlow services that ask ФЛ/ЮЛ on step 1)
# ---------------------------------------------------------------------------

def _generic_intent_block(service_id: str, lang: str) -> str:
    svc = _registry.get_service(service_id)
    if not svc:
        return ""
    label = svc.display_name.get(lang) or svc.display_name.get("ru") or service_id
    nav = svc.navigation_path.get(lang) or svc.navigation_path.get("ru") or ""
    if lang == "kz":
        return (
            f"=== ЕГЕР Интент = «{label}» ===\n"
            f"- <navigation_facts> ішінен жол жолын бір рет ғана көрсет — тек <step_control> жоқ немесе ағымдағы қадам = 1 болса. Қадам ≥ 2 болса навигацияны көрсетпе.\n"
            f"  Форматы: {nav}\n"
            f"- 1-ҚАДАМДА тұлға түрін (ЖТ/ЗТ) нақтылап ал, егер <intent_context> ішінде көрсетілмесе.\n"
            f"- Бір уақытта тек БІР қадамды көрсет.\n"
            f"- Ағымдағы қадам <step_control> арқылы беріледі. Қадамды өз бетіңше анықтама.\n"
            f"- Соңғы қадамнан кейін қол қою және жіберу нұсқаулығын бер."
        )
    return (
        f"=== ЕСЛИ Интент = «{label}» ===\n"
        f"- Покажи путь к разделу из <navigation_facts> один раз — только если <step_control> отсутствует или текущий шаг = 1. При шагах ≥ 2 навигацию не показывай.\n"
        f"  Формат: {nav}\n"
        f"- На шаге 1 уточни тип лица (ФЛ/ЮЛ), если не указан в <intent_context>.\n"
        f"- Показывай ОДИН шаг за раз.\n"
        f"- Текущий шаг передаётся в <step_control>. Не определяй шаг самостоятельно.\n"
        f"- После последнего шага — инструкция по подписи и отправке."
    )


