def _build_system_prompt(
    language: str,
    history: str,
    intent: Optional[str],
    entity: Optional[str],
    current_step: Optional[int],
    page: Optional[str],
    situation: Optional[str] = None,
) -> str:
    static = _STATIC_PROMPT_KZ if language == "kz" else _STATIC_PROMPT_RU
    dynamic_parts: list[str] = []

    if history:
        dynamic_parts.append(f"<history>\n{history}\n</history>")

    if intent or entity or page or situation:
        intent_label = _INTENT_LABELS.get(intent or "", "не определён")
        ctx_lines = [
            f"Интент: {intent_label}",
            f"Тип пользователя: {entity or 'не определено'}",
            f"Страница: {page or 'не указана'}",
        ]
        if situation:
            ctx_lines.append(f"Выбранная ситуация: {situation}")
        dynamic_parts.append(
            "<intent_context>\n" + "\n".join(ctx_lines) + "\n</intent_context>"
        )

    if current_step is not None:
        next_step = current_step + 1
        if current_step < 5:
            if language == "kz":
                step_note = (
                    "После инструкции добавь: «Барлық міндетті өрістерді толтырғаннан кейін "
                    "келесі қадамға өту үшін **Әрі қарай** батырмасын басыңыз.»"
                )
            else:
                step_note = (
                    "После инструкции добавь: «После заполнения всех обязательных полей "
                    "нажмите кнопку **Далее**, чтобы перейти к следующему шагу.»"
                )
        else:
            step_note = (
                "Это ПОСЛЕДНИЙ шаг. Дай инструкцию по подписи и отправке. НИКОГДА не предлагай шаг 6. "
                "После инструкции добавь: «После отправки статус заявки и готовые ТУ появятся в "
                "**Личный кабинет → Услуги → вкладка Обращения**.»"
            )
        dynamic_parts.append(
            f"<step_control>\n"
            f"Текущий шаг: {current_step} из 5\n"
            f"Отвечай СТРОГО по шагу {current_step}. Не включай другие шаги.\n"
            f"{step_note}\n"
            f"</step_control>"
        )

    if dynamic_parts:
        return static + "\n\n" + "\n\n".join(dynamic_parts)
    return static


