def _build_system_prompt(
    language: str,
    history: str,
    intent: Optional[str],
    entity: Optional[str],
    current_step: Optional[int],
    page: Optional[str],
    situation: Optional[str] = None,
) -> str:
    static = _STATIC_PROMPT_KZ if language == "kz" else _STATIC_PROMPT_RU
    dynamic_parts: list[str] = []

    if history:
        dynamic_parts.append(f"<history>\n{history}\n</history>")

    if intent or entity or page or situation:
        intent_label = _INTENT_LABELS.get(intent or "", "не определён")
        ctx_lines = [
            f"Интент: {intent_label}",
            f"Тип пользователя: {entity or 'не определено'}",
            f"Страница: {page or 'не указана'}",
        ]
        if situation:
            ctx_lines.append(f"Выбранная ситуация: {situation}")
        dynamic_parts.append(
            "<intent_context>\n" + "\n".join(ctx_lines) + "\n</intent_context>"
        )

    if current_step is not None:
        next_step = current_step + 1
        if current_step < 5:
            if language == "kz":
                step_note = (
                    "После инструкции добавь: «Барлық міндетті өрістерді толтырғаннан кейін "
                    "келесі қадамға өту үшін **Әрі қарай** батырмасын басыңыз.»"
                )
            else:
                step_note = (
                    "После инструкции добавь: «После заполнения всех обязательных полей "
                    "нажмите кнопку **Далее**, чтобы перейти к следующему шагу.»"
                )
        else:
            step_note = (
                "Это ПОСЛЕДНИЙ шаг. Дай инструкцию по подписи и отправке. НИКОГДА не предлагай шаг 6. "
                "После инструкции добавь: «После отправки статус заявки и готовые ТУ появятся в "
                "**Личный кабинет → Услуги → вкладка Обращения**.»"
            )
        dynamic_parts.append(
            f"<step_control>\n"
            f"Текущий шаг: {current_step} из 5\n"
            f"Отвечай СТРОГО по шагу {current_step}. Не включай другие шаги.\n"
            f"{step_note}\n"
            f"</step_control>"
        )

    if dynamic_parts:
        return static + "\n\n" + "\n\n".join(dynamic_parts)
    return static


# ---------------------------------------------------------------------------
# Public interface
# ---------------------------------------------------------------------------

async def ask_llm(
    question: str,
    context: str,
    page: Optional[str] = None,
    language: str = "ru",
    history: str = "",
    intent: Optional[str] = None,
    entity: Optional[str] = None,
    current_step: Optional[int] = None,
    situation: Optional[str] = None,
) -> str:
    system = _build_system_prompt(
        language=language,
        history=history,
        intent=intent,
        entity=entity,
        current_step=current_step,
        page=page,
        situation=situation,
    )
    prompt = f"<context>\n{context}\n</context>\n\n<question>\n{question}\n</question>\n\n<answer>"

    if LLM_PROVIDER == "openai":
        return await _call_openai(system, prompt)
    return await _call_ollama(system, prompt)


# ---------------------------------------------------------------------------
# Provider implementations
# ---------------------------------------------------------------------------

async def _call_openai(system: str, prompt: str) -> str:
    async with httpx.AsyncClient(timeout=30.0) as client:
        try:
            response = await client.post(
                "https://api.openai.com/v1/chat/completions",
                headers={
                    "Authorization": f"Bearer {OPENAI_API_KEY}",
                    "Content-Type": "application/json",
                },
                json={
                    "model": OPENAI_MODEL,
                    "messages": [
                        {"role": "system", "content": system},
                        {"role": "user", "content": prompt},
                    ],
                    "temperature": 0.0,
                    "max_tokens": 1000,
                },
            )
            data = response.json()
            if response.status_code != 200:
                error_msg = data.get("error", {}).get("message", "Unknown error")
                return f"Ошибка OpenAI: {error_msg}"
            return data["choices"][0]["message"]["content"]
        except Exception as e:
            return f"Ошибка LLM-сервиса: {str(e)}"


async def _call_ollama(system: str, prompt: str) -> str:
    async with httpx.AsyncClient(timeout=180.0) as client:
        try:
            response = await client.post(
                f"{OLLAMA_BASE_URL}/api/generate",
                json={
                    "model": OLLAMA_MODEL,
                    "prompt": prompt,
                    "system": system,
                    "stream": False,
                    "options": {"temperature": 0.0},
                },
            )
            data = response.json()
            return data.get("response", "Ошибка генерации.")
        except Exception as e:
            return f"Ошибка LLM-сервиса: {str(e)}"
