def normalize_kz(message: str) -> str:
    """Return message with transliterated Kazakh replaced by proper Kazakh Cyrillic.

    No-op when the message already contains Kazakh-specific characters.
    """
    if any(ch in _KZ_CHARS for ch in message):
        return message
    result = message.lower()
    for src, dst in sorted(_TRANSLIT_MAP.items(), key=lambda x: -len(x[0])):
        result = result.replace(src, dst)
    return result
